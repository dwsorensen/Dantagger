"""Builds Dantagger (CMake is not installed on the lab PC; g++ is driven directly).

    python3 build.py              # Python module python/Dantagger/_dantagger*.so and the tdcctl CLI
    python3 build.py --tests      # + C++ tests (host library, core), run them
    python3 build.py --asan       # the C++ tests under AddressSanitizer + UBSan
    python3 build.py --bench      # + benchmarks (build/bench)
    python3 build.py --app        # + the Dantagger app (build/app/dantagger, portable copy in build/app/dist/)
    python3 build.py --all        # everything above

Objects are cached in build/obj and rebuilt when their source, their flags or
any project header changed (third-party objects only when their source did).
Run it with the Python whose headers the module is for (the SDE venv's 3.12).
Flags: -O3 -march=x86-64-v3 (AVX2; every x86 CPU since ~2015).  The PC is
shared: -j defaults to 2.
"""

import argparse
import concurrent.futures
import pathlib
import shutil
import subprocess
import sys
import sysconfig

ROOT = pathlib.Path(__file__).resolve().parent
BUILD = ROOT / "build"
TP = ROOT / "third_party"
D3XX = TP / "ftd3xx" / "1.1.8"
IMGUI = TP / "imgui" / "1.90.9-docking"
IMPLOT = TP / "implot" / "0.16"
GLFW = TP / "glfw" / "3.4"
PFD = TP / "portable-file-dialogs" / "0.1.0"
PYBIND = TP / "pybind11" / "include"

HOST = ROOT / "host"
HOST_CORE = [HOST / "src" / f"{f}.cpp" for f in ("protocol", "tdc_protocol", "tdc_session", "run_file", "histogram",
                                                 "gauss_fit")]
HOST_D3XX = [HOST / "src" / f"{f}.cpp" for f in ("ft601_config", "sha256", "config_workflow", "d3xx_common",
                                                 "d3xx_transport")]
CORE = sorted((ROOT / "core").glob("*.cpp"))
APP = sorted((ROOT / "app").glob("*.cpp"))
INCLUDES = [ROOT / "core", HOST / "include", HOST / "src"]
WARN = ["-Wall", "-Wextra"]
HOST_WARN = ["-Wpedantic", "-Wconversion", "-Werror"]   # TDC_Firmware's discipline for its own files

_newest_header = None


def newest_header():
    global _newest_header
    if _newest_header is None:
        hs = []
        for d in (HOST, ROOT / "core", ROOT / "app"):
            hs += [p for p in d.rglob("*.hpp") if "_orig" not in p.parts]
        _newest_header = max((h.stat().st_mtime for h in hs), default=0)
    return _newest_header


def compile_one(src, obj, flags, project=True):
    lang = "gcc" if src.suffix == ".c" else "g++"
    deps = max(src.stat().st_mtime, newest_header() if project else 0)
    flag_file = obj.with_suffix(".flags")
    if obj.exists() and obj.stat().st_mtime > deps and flag_file.exists() and flag_file.read_text() == " ".join(flags):
        return obj
    obj.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run([lang, *flags, "-c", str(src), "-o", str(obj)], capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit(f"compile failed: {src}")
    if r.stderr.strip():
        sys.stderr.write(r.stderr)
    flag_file.write_text(" ".join(flags))
    return obj


def compile_all(sources, tag, flags, jobs, project=True):
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as ex:
        futs = [ex.submit(compile_one, s, BUILD / "obj" / tag / (s.stem + ".o"), flags, project) for s in sources]
        return [f.result() for f in futs]


def link(objs, out, extra):
    out.parent.mkdir(parents=True, exist_ok=True)
    r = subprocess.run(["g++", *[str(o) for o in objs], "-o", str(out), *extra], capture_output=True, text=True)
    if r.returncode != 0:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit(f"link failed: {out}")


def run(exe, *args):
    print(f"running {exe.relative_to(ROOT)}", flush=True)
    r = subprocess.run([str(exe), *args])
    if r.returncode != 0:
        raise SystemExit(f"{exe.name} FAILED")


def lib_objects(tag, flags, jobs):
    """Host library (TDC_Firmware discipline) + Dantagger core."""
    return (compile_all(HOST_CORE + HOST_D3XX, tag + "_host", flags + HOST_WARN, jobs) +
            compile_all(CORE, tag + "_core", flags, jobs))


def fonts_source():
    out = BUILD / "gen" / "fonts_data.cpp"
    srcs = [IMGUI / "fonts" / "Roboto-Medium.ttf", IMGUI / "fonts" / "Cousine-Regular.ttf"]
    if out.exists() and out.stat().st_mtime > max(s.stat().st_mtime for s in srcs):
        return out
    parts = ["// Generated by build.py from third_party/imgui/1.90.9-docking/fonts.\n#include <cstddef>\n"]
    for sym, src in zip(("roboto", "cousine"), srcs):
        data = src.read_bytes()
        parts.append(f"extern const unsigned char k_font_{sym}[] = {{{','.join(str(b) for b in data)}}};\n"
                     f"extern const std::size_t k_font_{sym}_size = {len(data)};\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(parts))
    return out


def build_app(lib, base, jobs):
    glfw_src = [GLFW / "src" / f"{f}.c" for f in (
        "context", "init", "input", "monitor", "platform", "vulkan", "window", "egl_context", "osmesa_context",
        "null_init", "null_monitor", "null_window", "null_joystick", "posix_module", "posix_time", "posix_thread",
        "posix_poll", "x11_init", "x11_monitor", "x11_window", "xkb_unicode", "glx_context", "linux_joystick")]
    glfw = compile_all(glfw_src, "glfw", ["-O2", "-D_GLFW_X11", "-D_DEFAULT_SOURCE", f"-I{GLFW / 'include'}"], jobs,
                       project=False)
    gui_src = [IMGUI / f"{f}.cpp" for f in ("imgui", "imgui_draw", "imgui_tables", "imgui_widgets")] + [
        IMGUI / "backends" / "imgui_impl_glfw.cpp", IMGUI / "backends" / "imgui_impl_opengl3.cpp",
        IMPLOT / "implot.cpp", IMPLOT / "implot_items.cpp"]
    gui = compile_all(gui_src, "imgui", ["-std=c++17", "-O2", f"-I{IMGUI}", f"-I{IMPLOT}", f"-I{GLFW / 'include'}"],
                      jobs, project=False)
    inc = [f"-isystem{p}" for p in (IMGUI, IMGUI / "backends", IMPLOT, GLFW / "include", PFD)] + [f"-I{ROOT / 'app'}"]
    app = compile_all(APP, "app", base + inc + ["-Wpedantic", "-Wconversion"], jobs)
    fonts = compile_all([fonts_source()], "app_gen", ["-std=c++17", "-O1"], 1, project=False)
    out = BUILD / "app" / "dantagger"
    link(lib + app + fonts + gui + glfw, out,
         ["-static-libstdc++", "-static-libgcc", f"-L{D3XX}", "-lftd3xx", "-Wl,-rpath,$ORIGIN",
          f"-Wl,-rpath,{D3XX}", "-pthread", "-ldl", "-lm"])
    dist = BUILD / "app" / "dist"
    dist.mkdir(parents=True, exist_ok=True)
    shutil.copy2(out, dist / "dantagger")
    shutil.copy2((D3XX / "libftd3xx.so").resolve(), dist / "libftd3xx.so")
    print(f"built {out.relative_to(ROOT)} (portable copy in {dist.relative_to(ROOT)}/)")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tests", action="store_true")
    ap.add_argument("--bench", action="store_true")
    ap.add_argument("--asan", action="store_true")
    ap.add_argument("--app", action="store_true")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("-j", type=int, default=2, help="parallel compiles (the PC is shared; default 2)")
    args = ap.parse_args()
    if args.all:
        args.tests = args.bench = args.asan = args.app = True

    inc = [f"-I{p}" for p in INCLUDES] + [f"-isystem{D3XX}"]
    base = ["-std=c++17", "-O3", "-march=x86-64-v3", "-fPIC", "-pthread", "-DNDEBUG", *WARN, *inc]
    d3xx_link = [f"-L{D3XX}", "-lftd3xx", "-pthread", f"-Wl,-rpath,{D3XX}"]
    lib = lib_objects("lib", base, args.j)

    # Python extension module.
    py_inc = sysconfig.get_paths()["include"]
    ext_flags = base + [f"-I{PYBIND}", f"-isystem{py_inc}", "-fvisibility=hidden"]
    mod = compile_all([ROOT / "core" / "python" / "module.cpp"], "ext", ext_flags, 1)
    out = ROOT / "python" / "Dantagger" / ("_dantagger" + sysconfig.get_config_var("EXT_SUFFIX"))
    link(lib + mod, out, ["-shared", f"-L{D3XX}", "-lftd3xx", "-pthread",
                          "-Wl,-rpath,$ORIGIN/../../third_party/ftd3xx/1.1.8"])
    print(f"built {out.relative_to(ROOT)}")

    # tdcctl command-line tool (TDC_Firmware's, unchanged).
    cli = compile_all([HOST / "src" / "tdcctl_main.cpp"], "cli", base + HOST_WARN, 1)
    link(lib + cli, BUILD / "tdcctl", d3xx_link)
    print("built build/tdcctl")

    if args.tests:
        tflags = [f for f in base if f != "-DNDEBUG"]
        host_t = compile_all([HOST / "tests" / "tdc_tests.cpp"], "tests_host", tflags + HOST_WARN, 1)
        link(lib + host_t, BUILD / "tdc_tests", d3xx_link)
        rtl = compile_all([HOST / "tests" / "rtl_frames.cpp"], "tests_host", tflags + HOST_WARN, 1)
        link(lib + rtl, BUILD / "rtl_frames", d3xx_link)
        core_t = compile_all([ROOT / "tests" / "cpp" / "test_core.cpp"], "tests_core", tflags, 1)
        link(lib + core_t, BUILD / "cpp_tests", d3xx_link)
        run(BUILD / "tdc_tests")
        run(BUILD / "cpp_tests")

    if args.asan:
        aflags = ["-std=c++17", "-O1", "-g", "-fsanitize=address,undefined", "-fno-omit-frame-pointer", "-fPIC",
                  "-pthread", *WARN, *inc]
        alib = lib_objects("asan", aflags, args.j)
        host_t = compile_all([HOST / "tests" / "tdc_tests.cpp"], "asan_tests_host", aflags + HOST_WARN, 1)
        core_t = compile_all([ROOT / "tests" / "cpp" / "test_core.cpp"], "asan_tests_core", aflags, 1)
        alink = d3xx_link + ["-fsanitize=address,undefined"]
        link(alib + host_t, BUILD / "tdc_tests_asan", alink)
        link(alib + core_t, BUILD / "cpp_tests_asan", alink)
        run(BUILD / "tdc_tests_asan")
        run(BUILD / "cpp_tests_asan")

    if args.bench:
        bench = compile_all([ROOT / "bench" / "bench_core.cpp"], "bench", base, 1)
        link(lib + bench, BUILD / "bench", d3xx_link)
        print("built build/bench")

    if args.app:
        build_app(lib, base, args.j)


if __name__ == "__main__":
    main()
